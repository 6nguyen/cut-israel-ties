#!/usr/bin/env bash
# Tests for scripts/doc-lint.sh (docs/specs/doc-placement.md §Behavior 4).
# Run: scripts/quiet-check.sh doc-lint
set -uo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
LINT="$HERE/scripts/doc-lint.sh"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT

PASS=0 FAIL=0
ok() { PASS=$((PASS + 1)); echo "PASS: $1"; }
bad() { FAIL=$((FAIL + 1)); echo "FAIL: $1"; }
check() { local name="$1"; shift; if "$@" >/dev/null 2>&1; then ok "$name"; else bad "$name"; fi; }
has() { check "$1" grep -qxF "$2" "$T/out"; }
put() { mkdir -p "$(dirname "$R/$1")"; printf '%s\n' "$2" >"$R/$1"; }

# Fixture: one violation per rule plus one allow line without a reason;
# everything else is placed.
R="$T/r"; mkdir -p "$R"; git -C "$R" init -q
put README.md "# r"
put sub/README.md "# sub tool"
put LICENSE.md "MIT"
put CLAUDE.md "# CLAUDE.md
## Area maps
<!-- comment -->
- api: \`api/CLAUDE.md\` — server
- ios: \`ios/CLAUDE.md\` — app
## Commands"
put api/CLAUDE.md "# api
## Purpose
Serves."
put ios/CLAUDE.md "# ios
## Entry points"
put .github/pull_request_template.md "x"
put .claude/skills/s/SKILL.md "x"
put docs/README.md "# where docs go"
put docs/FEATURES.md "# features"
put docs/old-plan.md "# plan"
put docs/guides/howto.md "# how"
put docs/prd/README.md "# prds"
put docs/prd/archive/.gitkeep ""
put docs/specs/README.md "# specs"
put docs/specs/good.md "# Good
## Purpose
p
\`\`\`
## Behavior
Status: in a fence
\`\`\`
## Behavior"
put docs/specs/bad.md "# Bad
## Behavior
b"
put docs/specs/diagram.png "png"
put docs/specs/assets/ok.png "png"
put docs/research/README.md "| Research | Question |
|---|---|
| [x](x.md) | q |
| [study](study/) | q |"
put docs/research/x.md "# x"
put docs/research/study/a.md "# a"
put docs/research/study/b.md "# b"
put docs/research/orphan.md "# orphan"
put tools/gen.md "generated"
put ops/notes.md "notes"
put docs/.doc-allow "# allowlist
tools/*  # generated by tools/gen.sh
ops/*"
git -C "$R" add -A && git -C "$R" -c user.email=t@t -c user.name=t commit -qm init
put notes/design.md "# untracked, not ignored"

"$LINT" "$R" >"$T/out" 2>&1; RC=$?
check "exit 1 on violations" test "$RC" = 1
has "rule 1: misplaced doc (untracked counts)" "notes/design.md:1: misplaced doc (see docs/README.md, or allowlist in docs/.doc-allow)"
has "rule 2: file directly in docs/" "docs/old-plan.md:1: only README.md, FEATURES.md and .doc-allow sit directly in docs/"
has "rule 3: first ## is not Purpose" "docs/specs/bad.md:2: first \`##\` heading must be \`## Purpose\`"
has "rule 4: map without Purpose" "ios/CLAUDE.md:1: area map has no \`## Purpose\` (listed at CLAUDE.md:5)"
has "rule 5: research file not indexed" "docs/research/orphan.md:1: not in the docs/research/README.md index"
has "rule 6: non-md outside assets/" "docs/specs/diagram.png:1: non-markdown file under docs/ outside an assets/ directory"
has "allow line needs a reason" "docs/.doc-allow:3: allow line needs \"  # <reason>\""
check "exactly those 7 violations" grep -q " 7 violations, 0 warnings$" "$T/out"
check "fenced Status/heading ignored, folder row covers files" sh -c "! grep -q 'good.md\|study/' '$T/out'"

# Rule 3 extras, rule 4/5 dangling pointers, README under docs/.
put docs/specs/status.md "# S
Status: SHIPPED
## Purpose"
python3 -c "print('# Big\n## Purpose\n' + 'x' * 16100)" >"$R/docs/specs/big.md"
put docs/research/README.md "| Research | Question |
|---|---|
| [x](x.md) | q |
| [study](study/) | q |
| [orphan](orphan.md) | q |
| [gone](gone.md) | q |"
put docs/foo/README.md "# foo"
sed -i.bak -e 's|`api/CLAUDE.md`|`api2/CLAUDE.md`|' -e 's|^## Commands|- web: see docs/web-map.md\
## Commands|' "$R/CLAUDE.md" && rm "$R/CLAUDE.md.bak"
"$LINT" "$R" >"$T/out" 2>&1
has "rule 3: Status line" "docs/specs/status.md:2: specs carry no \`Status:\` line (current truth, not a plan)"
check "rule 3: size cap" grep -q '^docs/specs/big.md:1: spec is 161[0-9][0-9] bytes (max 16000' "$T/out"
has "rule 4: missing map" "CLAUDE.md:4: Area maps line points at missing api2/CLAUDE.md"
has "rule 4: line names no map" "CLAUDE.md:6: Area maps line names no \`<dir>/CLAUDE.md\`"
has "rule 5: dangling index row" "docs/research/README.md:6: index row points at missing gone.md"
has "rule 1: README under docs/ outside a placed folder" "docs/foo/README.md:1: misplaced doc (see docs/README.md, or allowlist in docs/.doc-allow)"

# Migration plan present: rules 1, 2, 6 warn; unknown rows in the footer.
put docs/prd/migration-plan.md "# Migration plan

## Files

| Path | Status | State/Delta | Last commit | Evidence | Class | Destination |
|---|---|---|---|---|---|---|
| \`notes/design.md\` | — | — | 2026-10-01 | x | doc:unknown | (in place) |
| docs/prd/a.md | — | — | 2026-10-01 | x | active | docs/prd/a.md |

## Capability groups"
"$LINT" "$R" >"$T/out" 2>&1
has "plan: placement warns" "warn: docs/old-plan.md:1: only README.md, FEATURES.md and .doc-allow sit directly in docs/"
has "plan: rule 6 warns" "warn: docs/specs/diagram.png:1: non-markdown file under docs/ outside an assets/ directory"
has "plan: rule 3 still fails" "docs/specs/bad.md:2: first \`##\` heading must be \`## Purpose\`"
has "plan: footer lists unknown rows" "  notes/design.md"
check "plan: known rows not in footer" sh -c "! grep -qx '  docs/prd/a.md' '$T/out'"
P="$T/p"; mkdir -p "$P/docs/prd"; git -C "$P" init -q
printf '# x\n' >"$P/docs/old.md"; cp "$R/docs/prd/migration-plan.md" "$P/docs/prd/"
"$LINT" "$P" >"$T/out" 2>&1; RC=$?
check "plan: placement-only issues exit 0" test "$RC" = 0
check "plan: count line" grep -q '^doc-lint: .* 0 violations, 1 warnings$' "$T/out"
rm "$P/docs/prd/migration-plan.md"
"$LINT" "$P" >"$T/out" 2>&1; RC=$?
check "no plan: the same issue fails" test "$RC" = 1

# --only: just the named paths (a commit's files), from inside the repo.
rm "$R/docs/prd/migration-plan.md"
(cd "$R" && "$LINT" --only docs/old-plan.md README.md docs/specs/bad.md) >"$T/out" 2>&1; RC=$?
check "only: exit 1 for a named violation" test "$RC" = 1
check "only: just the named paths" sh -c "test \$(grep -c ':[0-9]*: ' '$T/out') = 2 && grep -q '^docs/old-plan.md:1:' '$T/out' && grep -q '^docs/specs/bad.md:2:' '$T/out'"
(cd "$R" && "$LINT" --only README.md docs/guides/howto.md) >"$T/out" 2>&1; RC=$?
check "only: clean paths pass in a dirty repo" test "$RC" = 0
(cd "$R" && "$LINT" --only) >"$T/out" 2>&1; RC=$?
check "only: no paths (nothing staged) passes" test "$RC" = 0

# The template itself.
s=$(python3 -c 'import time; print(time.time())')
"$LINT" "$REPO" >"$T/out" 2>&1; RC=$?
ms=$(python3 -c "import time; print(int((time.time() - $s) * 1000))")
check "this repo: 0 violations" test "$RC" = 0
echo "perf: ${ms} ms for $(tail -n1 "$T/out")"
check "this repo: <1 s" test "$ms" -lt 1000

# A repo without docs/specs/ (pre-migration): no git warning on stderr.
N="$T/nospecs"; mkdir -p "$N"; git -C "$N" init -q; mkdir -p "$N/docs"; printf "# n\\n" >"$N/docs/README.md"
"$LINT" "$N" >/dev/null 2>"$T/err"
check "no docs/specs: stderr empty" test ! -s "$T/err"

echo "$PASS passed, $FAIL failed"
[ "$FAIL" = 0 ]
