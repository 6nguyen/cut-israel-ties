#!/usr/bin/env bash
# Tests for scripts/features.sh (docs/prd/archive/2026-10-feature-list.md §1).
# Run: scripts/quiet-check.sh features
set -uo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
FE="$HERE/scripts/features.sh"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT

PASS=0 FAIL=0
ok() { PASS=$((PASS + 1)); echo "PASS: $1"; }
bad() { FAIL=$((FAIL + 1)); echo "FAIL: $1"; }
check() { local name="$1"; shift; if "$@" >/dev/null 2>&1; then ok "$name"; else bad "$name"; fi; }
gitq() { git -C "$R" -c user.name=t -c user.email=t@t "$@" >/dev/null; }

spec() { printf '# %s\n\n## Purpose\nx\n' "$1" >"$R/docs/specs/$1.md"; }
prd() {  # prd <name> <status line rest> <sections block> <delta block>
  printf '# %s — PRD\nStatus: %s\n\n## Problem\nx\n\n## Expected behavior\n### 1. One\nx\n\n## Spec delta\n%s\n\n## Acceptance criteria\n- [ ] x\n\n## State (updated 2026-10-01)\n- Sections:\n%s\n\n## Changes\n- x\n' \
    "$1" "$2" "$4" "$3" >"$R/docs/prd/$1.md"
}

# --- Fixture: one row per state, precedence, Next rows, archive -------------
R="$T/repo"; mkdir -p "$R/docs/specs" "$R/docs/prd/archive"
git -C "$R" init -q
for s in alpha beta gamma delta epsilon; do spec $s; done
cat >"$R/docs/specs/README.md" <<'MD'
# Specs

## Index (the feature set)
| Spec | Capability | Owner surfaces |
|---|---|---|
| [alpha](alpha.md) | Alpha does a thing | a |
| [beta](beta.md) | Beta capability with a description long enough to be cut at sixty characters | b |
| [gamma](gamma.md) | Gamma | c |
| [delta](delta.md) | Delta | d |
| [epsilon](epsilon.md) | Epsilon | e |
MD
cat >"$R/docs/prd/README.md" <<'MD'
# PRDs

## Index (open changes only)
| PRD | Status | Owner surfaces |
|---|---|---|

## Next (ideas without a PRD, in intended order; ≤10)
| # | Idea | Targets | Notes |
|---|---|---|---|
| 1 | Epsilon export to CSV | epsilon | |
| 2 | Brand new widget | new | |
MD
prd pin-beta "APPROVED 2026-10-01 · Owner: o · Last updated: 2026-10-03" "  - [ ] 1. One" '- MODIFIED `docs/specs/beta.md` §Behavior 2'
prd build-gamma "APPROVED 2026-10-01 · Owner: o · Last updated: 2026-10-04" "  - [x] 1. One · PR #1 merged
  - [ ] 2. Two" '- MODIFIED `docs/specs/gamma.md` §Behavior'
prd also-gamma "DRAFT 2026-10-01 · Owner: o · Last updated: 2026-10-02" "  - [ ] 1. One" '- MODIFIED `docs/specs/gamma.md` §Purpose'
prd retire-delta "APPROVED 2026-10-01 · Owner: o · Last updated: 2026-10-05" "  - [~] 1. One · feat/x" '- REMOVED `docs/specs/delta.md`: whole capability retired'
prd new-thing "APPROVED 2026-10-01 · Owner: o · Last updated: 2026-10-06" "  - [ ] 1. One" '- ADDED `docs/specs/new-thing.md`'
prd status-building "BUILDING 2026-10-01 · Owner: o · Last updated: 2026-10-07" "" 'none — internal'
prd old-idea "SUPERSEDED by new-thing · Owner: o" "  - [ ] 1. One" '- MODIFIED `docs/specs/alpha.md`'
prd repo-setup "APPROVED 2026-10-01 (adopt) · Owner: o" "  - [ ] 1. One" 'none — setup'
prd partial-remove "APPROVED 2026-10-01 · Owner: o · Last updated: 2026-10-01" "  - [ ] 1. One" '- REMOVED `docs/specs/alpha.md` §Behavior 3'
mv "$R/docs/prd/partial-remove.md" "$R/docs/prd/archive/2026-09-partial-remove.md"
prd drop-zeta "SHIPPED 2026-09-20 (PR #9) · Owner: o" "  - [x] 1. One" '- REMOVED `docs/specs/zeta.md`'
mv "$R/docs/prd/drop-zeta.md" "$R/docs/prd/archive/2026-09-drop-zeta.md"
gitq add -A && gitq commit -m fixture

out="$("$FE" "$R" 2>&1)"; rc=$?
[ $rc = 0 ] && ok "write exits 0" || bad "write exits 0 ($rc: $out)"
F="$R/docs/FEATURES.md"
row() { grep "^| $1 |" "$F"; }
state() { row "$1" | awk -F' \\| ' '{print $2}'; }
check "line 1 title" test "$(sed -n 1p "$F")" = "# Features"
check "line 2 generated comment" grep -q '^<!-- generated by features.sh .* do not edit -->$' <(sed -n 2p "$F")
check "count line" test "$(sed -n 4p "$F")" = "2 building · 2 pinned · 1 deprecated · 2 planned · 1 shipped · 1 removed"
check "table header" grep -qx '| Feature | State | What it does | Spec | Change | Updated |' "$F"
check "SHIPPED: spec with nothing open" test "$(state alpha)" = SHIPPED
check "PINNED: non-building PRD names spec" test "$(state beta)" = PINNED
check "BUILDING: [x] item, beats PINNED" test "$(state gamma)" = BUILDING
check "DEPRECATED: whole-file REMOVED beats BUILDING" test "$(state delta)" = DEPRECATED
check "PINNED: Next row targets spec" test "$(state epsilon)" = PINNED
check "PLANNED: PRD adding a new spec" test "$(state new-thing)" = PLANNED
check "BUILDING: Status BUILDING without Sections" test "$(state status-building)" = BUILDING
check "PLANNED: Next row targeting new" test "$(state brand-new-widget)" = PLANNED
check "REMOVED: archived SHIPPED whole-file REMOVED" test "$(state zeta)" = REMOVED
check "SUPERSEDED PRD not listed" test -z "$(row old-idea)"
check "repo-setup not listed" test -z "$(row repo-setup)"
check "partial REMOVED (§) does not deprecate" test "$(state alpha)" = SHIPPED
check "change: k/n and +others" grep -qF '| gamma | BUILDING | Gamma | [spec](specs/gamma.md) | [build-gamma](prd/build-gamma.md) 1/2 +1 | 2026-10-04 |' "$F"
check "change: Next #n" grep -qF '| epsilon | PINNED | Epsilon | [spec](specs/epsilon.md) | Next #1 |' "$F"
check "change: Status word without Sections" grep -qF '[status-building](prd/status-building.md) BUILDING | 2026-10-07 |' "$F"
check "removed: archive link and SHIPPED date" grep -qF '| zeta | REMOVED | - | - | [2026-09-drop-zeta](prd/archive/2026-09-drop-zeta.md) | 2026-09-20 |' "$F"
check "what: PRD title without — PRD" grep -qF '| new-thing | PLANNED | new-thing | - |' "$F"
what_beta="$(row beta | awk -F' \\| ' '{print $3}')"
check "what: cut at 60 characters" test "$(printf '%s' "$what_beta" | python3 -c 'import sys; print(len(sys.stdin.read()))')" = 60
check "updated: spec last commit date" grep -qE "^\| alpha \| SHIPPED .* \| $(git -C "$R" log -1 --format=%cs) \|$" "$F"
order="$(awk -F' \\| ' '/^\| [a-z]/ && NR > 7 {printf "%s:%s ", $1, $2}' "$F" | sed 's/| //g')"
check "order: states, Next order, then names" test "$order" = "gamma:BUILDING status-building:BUILDING beta:PINNED epsilon:PINNED delta:DEPRECATED brand-new-widget:PLANNED new-thing:PLANNED alpha:SHIPPED zeta:REMOVED "
[ "$order" = "gamma:BUILDING status-building:BUILDING beta:PINNED epsilon:PINNED delta:DEPRECATED brand-new-widget:PLANNED new-thing:PLANNED alpha:SHIPPED zeta:REMOVED " ] || echo "  got: $order"

cp "$F" "$T/first"
out="$("$FE" "$R")"
check "rerun: byte-identical" cmp -s "$F" "$T/first"
check "rerun: says unchanged" grep -q unchanged <<<"$out"
check "--check passes when current" "$FE" --check "$R"
sed -i.bak '2s/APPROVED/BUILDING/' "$R/docs/prd/pin-beta.md" && rm "$R/docs/prd/pin-beta.md.bak"
out="$("$FE" --check "$R")"; rc=$?
check "--check fails after a Status edit" test $rc = 1
check "--check message" grep -qx 'docs/FEATURES.md: stale, run features.sh' <<<"$out"
check "--check writes nothing" cmp -s "$F" "$T/first"
check "--json is a list of six-key rows" python3 -c '
import json, sys
rows = json.loads(sys.stdin.read())
assert rows and all(set(r) == {"feature", "state", "what", "spec", "change", "updated"} for r in rows)' <<<"$("$FE" --json "$R")"

# --- 60-row cap, missing dirs ----------------------------------------------------
R="$T/big"; mkdir -p "$R/docs/specs"; git -C "$R" init -q
for i in $(seq 1 61); do spec "s$i"; done
"$FE" "$R" >"$T/big.out"
check "over 60: file still written" test -f "$R/docs/FEATURES.md"
check "over 60: write warns" grep -qx 'docs/FEATURES.md: over 60 rows; group specs or trim' "$T/big.out"
out="$("$FE" --check "$R")"; rc=$?
check "over 60: --check exit 1" test $rc = 1
check "over 60: --check message" grep -qx 'docs/FEATURES.md: over 60 rows; group specs or trim' <<<"$out"

mkdir -p "$T/empty"; git -C "$T/empty" init -q
"$FE" "$T/empty" >/dev/null 2>&1; rc=$?
check "no docs/specs and no docs/prd: exit 2" test $rc = 2

# --- Shallow clone: spec dates need history (CI checkout default is depth 1) --
R="$T/deep"; mkdir -p "$R/docs/specs"; git -C "$R" init -q
spec alpha
GIT_COMMITTER_DATE=2026-01-01T12:00:00 gitq add -A
GIT_COMMITTER_DATE=2026-01-01T12:00:00 gitq commit -m spec
"$FE" "$R" >/dev/null; gitq add -A
GIT_COMMITTER_DATE=2026-02-01T12:00:00 gitq commit -m features
git clone -q --depth 1 "file://$R" "$T/shallow" 2>/dev/null
"$FE" --check "$T/shallow" >"$T/out" 2>&1; rc=$?
check "shallow: --check fails with the cause, not 'stale'" sh -c "test $rc = 1 && grep -qF 'docs/FEATURES.md: shallow clone; spec dates need full history (actions/checkout fetch-depth: 0)' '$T/out' && ! grep -q stale '$T/out'"
"$FE" "$T/shallow" >"$T/out" 2>&1; rc=$?
check "shallow: write refuses (exit 2), file unchanged" sh -c "test $rc = 2 && git -C '$T/shallow' diff --quiet"
git clone -q "file://$R" "$T/full" 2>/dev/null
check "full clone: --check passes" "$FE" --check "$T/full"

# --- Uncommitted specs: dated today, so a pre-commit run survives the commit --
R="$T/dirty"; mkdir -p "$R/docs/specs"; git -C "$R" init -q
spec alpha; spec gamma
GIT_COMMITTER_DATE=2026-01-01T12:00:00 gitq add -A
GIT_COMMITTER_DATE=2026-01-01T12:00:00 gitq commit -m specs
printf 'more\n' >>"$R/docs/specs/alpha.md"; spec beta
"$FE" "$R" >/dev/null
today=$(date +%F); F="$R/docs/FEATURES.md"
check "dirty: untracked spec dated today" sh -c "grep '^| beta |' '$F' | grep -qF '| $today |'"
check "dirty: edited spec dated today" sh -c "grep '^| alpha |' '$F' | grep -qF '| $today |'"
check "dirty: clean spec keeps its commit date" sh -c "grep '^| gamma |' '$F' | grep -qF '| 2026-01-01 |'"
gitq add -A && gitq commit -m "edit alpha, add beta"
check "dirty: --check passes after the commit" "$FE" --check "$R"

# --- Budget: 100 PRDs under 1 s ------------------------------------------------------
R="$T/perf"; mkdir -p "$R/docs/specs" "$R/docs/prd"; git -C "$R" init -q
for i in $(seq 1 40); do spec "c$i"; done
for i in $(seq 1 100); do prd "p$i" "APPROVED 2026-10-01 · Owner: o · Last updated: 2026-10-01" "  - [ ] 1. One" "- MODIFIED \`docs/specs/c$((i % 40 + 1)).md\` §Behavior"; done
gitq add -A && gitq commit -m perf
start=$(python3 -c 'import time; print(time.time())')
"$FE" "$R" >/dev/null
ms=$(python3 -c "import time; print(int((time.time() - $start) * 1000))")
echo "budget: 100 PRDs + 40 specs in ${ms} ms"
check "budget: < 1000 ms on 100 PRDs" test "$ms" -lt 1000

echo "RESULT: $PASS passed, $FAIL failed"
[ $FAIL = 0 ]
